create table public.todos (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 180),
  completed boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.todos enable row level security;

create policy "Anyone can read demo todos"
  on public.todos for select
  to anon, authenticated
  using (true);

create policy "Anyone can add demo todos"
  on public.todos for insert
  to anon, authenticated
  with check (true);

create policy "Anyone can update demo todos"
  on public.todos for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "Anyone can delete demo todos"
  on public.todos for delete
  to anon, authenticated
  using (true);

grant select, insert, update, delete on public.todos to anon, authenticated;
grant usage, select on sequence public.todos_id_seq to anon, authenticated;